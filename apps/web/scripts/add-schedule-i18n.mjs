function deepMerge(target, source) {
	for (const [key, value] of Object.entries(source)) {
		if (value && typeof value === 'object' && !Array.isArray(value)) {
			if (!target[key] || typeof target[key] !== 'object') {
				target[key] = {};
			}
			deepMerge(target[key], value);
		} else if (!(key in target)) {
			target[key] = value;
		}
	}
}

for (const [locale, additions] of Object.entries(T)) {
	const file = join(localesDir, `${locale}.json`);
	const json = JSON.parse(readFileSync(file, 'utf8'));
	json.nav = json.nav ?? {};
	json.dashboard = json.dashboard ?? {};
	json.sync = json.sync ?? {};
	deepMerge(json.nav, additions.nav);
	deepMerge(json.dashboard, additions.dashboard);
	json.sync.schedule = json.sync.schedule ?? {};
	deepMerge(json.sync.schedule, additions.schedule);
	writeFileSync(file, `${JSON.stringify(json, null, '\t')}\n`, 'utf8');
	console.log(`updated ${locale}.json`);
}
